SET TERM ; ^

-- ============================================
-- 4. 트리거 확인
-- ============================================

SELECT
    RDB$TRIGGER_NAME,
    RDB$RELATION_NAME,
    RDB$TRIGGER_TYPE,
    RDB$TRIGGER_INACTIVE
FROM RDB$TRIGGERS
WHERE RDB$RELATION_NAME IN ('CUSTOMS', 'GOODS')
  AND RDB$SYSTEM_FLAG = 0
ORDER BY RDB$RELATION_NAME, RDB$TRIGGER_NAME;

COMMIT;
